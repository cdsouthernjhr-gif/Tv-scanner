"""Generate the sample reports in docs/samples from the synthetic demo scenario.

    python tools/make_samples.py

All data is synthetic ("Acme", "TESTTV55", generated firmware/datasheets/photos). Nothing is downloaded.
"""
from __future__ import annotations

import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "tests")]


def main() -> int:
    from keyring.backends import fail

    import demo_scenario
    from app.core.context import AppContext
    from app.modules.reports.report_center import REPORT_TYPES
    from app.security.secrets import SecretStore

    out = ROOT / "docs" / "samples"
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    with tempfile.TemporaryDirectory() as td:
        ctx = AppContext.create(Path(td) / "data")
        ctx.secrets = ctx.finder.secrets = SecretStore(backend=fail.Keyring())
        ids = demo_scenario.build(ctx, Path(td) / "work")
        made = []
        for rtype, (title, kind) in REPORT_TYPES.items():
            fmts = ("pdf", "html") if rtype != "hardware" else ("pdf", "html", "xlsx", "csv", "json")
            for fmt in fmts:
                src = ctx.report_center.generate(rtype, ids[kind], fmt)
                dest = out / f"{rtype}.{fmt}"
                shutil.copyfile(src, dest)
                made.append(dest)
        ctx.close()
    (out / "README.md").write_text(
        "# Sample reports\n\nGenerated by `python tools/make_samples.py` from a **synthetic** demonstration scenario "
        "(fictional brand *Acme*, model *TESTTV55*, generated firmware images, datasheets and photos). They show the "
        "layout and content of each report; they are not results for a real TV.\n\n"
        "| Report | Files |\n|---|---|\n" +
        "\n".join(f"| {title} | " + ", ".join(f"[{p.suffix[1:].upper()}]({p.name})" for p in sorted(made)
                                                if p.stem == rtype) + " |"
                  for rtype, (title, _) in REPORT_TYPES.items()) + "\n", encoding="utf-8")
    total = sum(p.stat().st_size for p in made)
    print(f"{len(made)} sample files, {total / 1024:.0f} KiB → {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
