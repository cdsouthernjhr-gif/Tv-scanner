"""End-to-end demo scenario through every module (synthetic data, clearly labelled).

Used by the integration test (all reports × all formats) and by tools/make_samples.py.
No network access: the firmware search uses recorded API responses.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

import firmware_builders as fb
from app.modules.firmware_finder.criteria import SearchCriteria
from app.modules.firmware_finder.http import RateLimiter
from app.services.project_service import TVProject
from fake_http import FakeResponse, FakeSession, github_release, github_repo
from synthetic_datasheets import ddr3_datasheet, make_datasheet
from synthetic_images import chip_marking, rear_label


def build(ctx, work: Path) -> dict:
    work.mkdir(parents=True, exist_ok=True)
    ids: dict = {}
    # 1 project + identification evidence
    p = ctx.projects.create(TVProject(name="SAMPLE — Bench TV (synthetic data)", manufacturer="Acme",
                                      model_number="TESTTV55", mainboard="TP.MS338.PB801", chassis="CH-9",
                                      firmware_version="V1.0", panel_model="LC550EGE", screen_size_inches=55,
                                      notes="Synthetic demonstration data generated by TV Intelligence Scanner"))
    ids["project"] = p.id
    ev = ctx.evidence.add_image(p.id, rear_label(work / "label.jpg", ["ACME", "Model: TESTTV55", "Serial No: SN0001",
                                                                       'LED TV 55"']), "tv_back_label", "rear label")
    chip = ctx.evidence.add_image(p.id, chip_marking(work / "chip.png", ["MSD6A648"]), "chip", "SoC marking")
    for e, lines in ((ev, [("ACME", 0.95), ("Model: TESTTV55", 0.93)]), (chip, [("MSD6A648", 0.94)])):
        from fake_ocr import install_fake_ocr
        install_fake_ocr(ctx, lines)
        ctx.identification.run_ocr(e.id)
    for c in ctx.identification.candidates(p.id):
        if c["field"] == "manufacturer" and c["value"] == "Acme" or c["field"] == "model_number":
            ctx.identification.accept_candidate(c["id"])
    m = ctx.identification.markings(p.id)[0]
    ctx.identification.confirm_marking(m["id"])
    # 2 hardware + datasheet
    ctx.datasheets.import_pdf(ddr3_datasheet(work / "ddr3.pdf"), vendor="Samsung (synthetic)")
    ctx.hardware.add_component(p.id, "ram", "K4B4G1646E-BYK0", quantity=2, position="U3")
    ctx.hardware.add_component(p.id, "flash", "W25Q64JVSIQ", position="U7")
    ctx.hardware.analyze_project(p.id)
    # 3 firmware: original (baseline) + official update
    orig, upd = work / "orig_dump.bin", work / "upgrade_tv_v2.bin"
    panel = {"vendor/config/panel/panel_lc550ege.ini": b"PanelName = LC550EGE\nm_wPanelWidth = 3840\n"}
    fb.composite(orig, "4.9.118", extra_file=b"board=TP.MS338.PB801", extra_files=panel)
    fb.composite(upd, "4.9.200", extra_file=b"board=TP.MS338.PB801", extra_files=panel)
    ro = ctx.library.import_file(orig, project_id=p.id, category="Original", manufacturer="Acme", model_number="TESTTV55")
    ctx.firmware.analyze(ro.id, use_binwalk=False)
    ids["firmware"] = ro.id
    # 4 search (recorded API responses) + verified download of the update
    ctx.config.set("network.offline_mode", False)
    sess = FakeSession()
    ctx.finder.http.session, ctx.finder.http.sleep, ctx.finder.http.limiter = sess, (lambda s: None), RateLimiter(1e4)
    payload = upd.read_bytes()
    sha = hashlib.sha256(payload).hexdigest()
    sess.add("GET", "api.github.com/search/repositories", FakeResponse(200, json_data={"items": [
        github_repo("acme-sample/testtv55-fw", "SAMPLE: TESTTV55 firmware for TP.MS338.PB801")]}))
    sess.add("GET", "api.github.com/repos/acme-sample/testtv55-fw/releases", FakeResponse(200, json_data=[
        github_release("acme-sample/testtv55-fw", "V2.0", [("upgrade_tv_v2.bin", len(payload), f"sha256:{sha}")])]))
    sess.add("GET", "github.com/acme-sample/testtv55-fw/releases/download",
             FakeResponse(200, payload, headers={"Content-Type": "application/octet-stream"}))
    sid = ctx.finder.search(SearchCriteria(manufacturer="Acme", model_number="TESTTV55", mainboard="TP.MS338.PB801",
                                           architecture="ARM (32-bit)"), p.id, ["GitHub"])
    ids["search_session"] = sid
    rid = [r for r in ctx.finder.results(sid) if r["file_name"] == "upgrade_tv_v2.bin"][0]["id"]
    out = ctx.finder.download(rid, analyze=True)
    ctx.db.execute("UPDATE firmware_files SET category='Official', version='V2.0' WHERE id=?", (out["firmware_id"],))
    ids["update_firmware"] = out["firmware_id"]
    ctx.config.set("network.offline_mode", True)
    # 5 software + service menu
    ctx.software.add_operator_fact(p.id, "firmware_version", "V1.0", None, "Settings > Support > About this TV")
    ctx.software.analyze(p.id)
    sm = make_datasheet(work / "service_manual.pdf", "Acme CH-9 Service Manual (synthetic)",
                        [["Contents"], ["4.2 Entering Service Mode", "Press MENU then 1 1 4 7 on the service remote."]])
    did = ctx.datasheets.import_pdf(sm, vendor="Acme")
    rec = ctx.service_menus.add({"manufacturer": "Acme", "model_pattern": "TESTTV*", "chassis": "CH-9",
                                 "menu_category": "Service Menu", "access_procedure": "MENU, 1, 1, 4, 7 (service remote)",
                                 "function_description": "White balance, option codes",
                                 "access_availability": "service remote required", "configuration_risk": "high",
                                 "backup_mechanism": "Service Menu > Data > Export to USB", "document_id": did,
                                 "document_page": 2})
    a = ctx.service_menus.plan_action(p.id, rec, "Panel option code", "12", "replacement panel fitted", "11")
    ctx.service_menus.record_backup(a, "settings exported to USB: acme_backup.dat")
    # 6 compatibility + upgrade (USB = folder)
    comp = ctx.compatibility.evaluate(p.id, out["firmware_id"])
    ids["compatibility"] = comp.id
    U = ctx.upgrades
    prof = U.add_profile({"manufacturer": "Acme", "model_pattern": "TESTTV*", "method": "official_usb",
                          "documentation_ref": "Acme TESTTV user manual (synthetic) p.40 'Software update via USB'",
                          "package_pattern": "upgrade_*.bin", "usb_filesystems": "FAT32", "usb_target_path": "/",
                          "power_requirements": "Do not switch off during the update",
                          "recovery_procedure": "If the TV does not start, contact Acme service (synthetic)"})
    U.verify_profile(prof, "VERIFIED Acme")
    us = U.start(p.id, prof, out["firmware_id"])
    for st in (U.step_identification, U.step_compatibility, U.step_validation):
        st(us)
    U.step_backup(us, "Settings exported via official menu (synthetic)")
    usb = work / "USB"
    usb.mkdir(exist_ok=True)
    probe = lambda t: {"fs": "FAT32", "free": 10 ** 10, "removable": True, "root": t}   # noqa: E731
    U.step_preparation(us, True, True, U.confirmation_phrase(us), str(usb), fs_probe=probe)
    U.step_execution(us, fs_probe=probe)
    U.step_verification(us, "V2.0", True, True, True, {f: True for f in ("picture", "sound", "remote", "network")})
    U.recovery_guidance(us)
    ids["upgrade_session"] = us
    return ids


